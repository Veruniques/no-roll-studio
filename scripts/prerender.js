#!/usr/bin/env node
/* Writes the portfolio's text into index.html so people and tools that don't run
   JavaScript can read it. site.js replaces this content when the page loads.
   Run after editing assets/js/data.js:  node scripts/prerender.js */
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.join(__dirname, '..');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'assets/js/data.js'), 'utf8'), ctx);
const D = ctx.window.NOROLL, A = D.about;
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const ul = l => (l && l.length ? `<ul>${l.map(i => `<li>${esc(i)}</li>`).join('')}</ul>` : '');
const p = t => (t ? `<p>${esc(t)}</p>` : '');
const h = (n, t) => (t ? `<h${n}>${esc(t)}</h${n}>` : '');
const projects = D.product.filter(x => !x.draft), main = projects.filter(x => !x.more), more = projects.filter(x => x.more);
const caseStudy = c => [
  `<section id="static-${c.id}">`, h(3, c.title), p(c.subtitle), p([c.type, c.client, c.production].filter(Boolean).join(' · ')),
  c.facts ? ul(c.facts.map(([n, l]) => `${n}: ${l}`)) : '', p(c.problem), p(c.text),
  c.decisions ? h(4, 'Key decisions') + ul(c.decisions) : '', c.stance ? h(4, 'Selling without tricks') + p(c.stance) : '', c.role ? h(4, 'My role') + ul(c.role) : '',
  c.quote ? `<blockquote>${esc(c.quote.text)} — ${esc(c.quote.who)}</blockquote>` : '',
  ...(c.chapters || []).map(ch => [h(4, ch.title), p(ch.kicker), p(ch.text), ul(ch.list),
    ...(ch.steps || []).map(s => h(5, s.title) + p(s.text) + ul(s.list))].join('')),
  `<p><a href="#${c.id}">Open the ${esc(c.title)} case study with images</a></p>`, '</section>'].join('');
const html = [
  '<h1>Veronika Dominiková, Product Designer</h1>',
  '<p>Monetization and complex flows. I co-led Ancillaries at Kiwi.com, with one goal: take revenue per booking from €2 to €25. I also built product research from zero at Keboola.</p>',
  p(A.path),
  `<p><a href="mailto:${D.owner.email}">${esc(D.owner.email)}</a> · <a href="${D.owner.linkedin}">LinkedIn</a> · <a href="resume.html">Full CV</a></p>`,
  h(2, 'Case studies'), ...main.map(caseStudy),
  h(2, 'How I work with agents'), ul(A.agents),
  h(2, 'CV'), ...A.cv.map(r => `<h3>${esc(r.what)}</h3>${p(`${r.where} · ${r.when}`)}${p(r.text)}`),
  h(2, 'Other work'), ...more.map(caseStudy),
  h(2, 'What people say'), ...A.references.map(r => `<blockquote>${esc(r.text)} — ${esc(r.who)}, ${esc(r.role)}${r.letter ? ` <a href="${r.letter}">Full letter (PDF)</a>` : ''}</blockquote>`),
  h(2, 'On stage'), ul(A.talks.map(t => t.what)),
  h(2, 'Skills and tools'), ul([...A.canDo, ...A.tools]),
].join('\n');
const file = path.join(root, 'index.html');
const page = fs.readFileSync(file, 'utf8');
const re = /<main id="view" tabindex="-1">[\s\S]*?<\/main>/;
if (!re.test(page)) throw new Error('main not found');
fs.writeFileSync(file, page.replace(re, () => `<main id="view" tabindex="-1"><!-- generated by scripts/prerender.js -->\n${html}\n</main>`));
console.log('index.html:', Math.round(html.length / 1024) + ' KB of text');
